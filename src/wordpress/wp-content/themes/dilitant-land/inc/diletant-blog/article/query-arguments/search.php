<?php
/**
 * Нормализация поискового запроса
 * публичной выборки статей.
 *
 * Нормативная основа:
 *     ТП-03 — Editorial
 *     EDC-01 — Article Model
 *     AM-D02 — Защита инвариантов WP_Query
 *
 * Ответственность:
 *     - проверка типа поискового запроса;
 *     - ограничение длины;
 *     - нормализация средствами WordPress;
 *     - формирование разрешённого аргумента s.
 *
 * Зависимости:
 *     article/constants.php
 *
 * @package Dilitant_Land
 */

defined( 'ABSPATH' ) || exit;


/**
 * Нормализует поисковый запрос.
 *
 * Допускается исключительно строка,
 * длина которой не превышает установленного
 * ограничения.
 *
 * Отсутствующий или пустой запрос
 * не ограничивает выборку.
 *
 * Некорректный тип или превышение
 * допустимой длины приводит к отказу.
 *
 * @internal
 *
 * @param array $args Исходные аргументы.
 *
 * @return array|null
 */
function dilitant_land_normalize_blog_search_args(
    $args
) {
    /*
     * Отсутствие поискового параметра
     * является допустимым.
     */
    if ( ! array_key_exists( 's', $args ) ) {
        return array();
    }


    /*
     * Проверяем тип значения.
     *
     * Не допускаем массивы, объекты,
     * логические и числовые значения.
     */
    if ( ! is_string( $args['s'] ) ) {
        return null;
    }


    /*
     * Проверяем длину исходного запроса
     * до выполнения нормализации.
     */
    if (
        strlen( $args['s'] ) >
        DILITANT_LAND_BLOG_MAX_SEARCH_LENGTH
    ) {
        return null;
    }


    /*
     * Нормализуем текст средствами WordPress.
     */
    $search = sanitize_text_field(
        $args['s']
    );


    /*
     * Пустой запрос не формирует
     * поискового ограничения.
     */
    if ( '' === $search ) {
        return array();
    }


    /*
     * Возвращаем исключительно
     * разрешённый параметр s.
     */
    return array(
        's' => $search,
    );
}