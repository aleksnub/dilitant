<?php
/**
 * Контроль доступа к отдельным статьям
 * блога «Дилетанты в Армении».
 *
 * Нормативная основа:
 *     ТП-03 — Editorial
 *     EDC-01 — Article Model
 *     AM-D03 — Публичная доступность
 *
 * Ответственность:
 *     - применение решений Article Model;
 *     - контроль доступа до рендеринга;
 *     - формирование HTTP 404;
 *     - исключение отклонённой записи
 *       из главного запроса;
 *     - блокировка канонического
 *       перенаправления при отказе;
 *     - запрет кэширования Preview.
 *
 * Компонент не определяет самостоятельно
 * публичную доступность статьи
 * или полномочия пользователя.
 *
 * @package Dilitant_Land
 */

defined( 'ABSPATH' ) || exit;


/**
 * Переводит главный запрос WordPress
 * в состояние HTTP 404.
 *
 * Отклонённая запись исключается
 * из результатов главного запроса.
 *
 * Это необходимо, поскольку set_404()
 * изменяет признаки запроса, но само
 * по себе не гарантирует удаления
 * ранее полученных публикаций.
 *
 * Выбор шаблона ошибки делегируется
 * стандартному механизму WordPress.
 *
 * @return void
 */
function dilitant_land_reject_blog_article(): void {
    global $wp_query;


    /*
     * Устанавливаем состояние
     * отсутствующей страницы.
     */
    if ( $wp_query instanceof WP_Query ) {
        $wp_query->set_404();


        /*
         * Удаляем публикации
         * из результата запроса.
         *
         * Резервный шаблон темы
         * не должен получить отклонённую
         * запись через have_posts().
         */
        $wp_query->posts = array();

        $wp_query->post_count = 0;

        $wp_query->found_posts = 0;

        $wp_query->max_num_pages = 0;


        /*
         * Сбрасываем состояние
         * цикла отображения.
         */
        $wp_query->current_post = -1;

        $wp_query->in_the_loop = false;

        $wp_query->post = null;


        /*
         * Исключаем дальнейшее
         * использование отклонённого
         * объекта запроса.
         */
        $wp_query->queried_object = null;

        $wp_query->queried_object_id = 0;
    }


    /*
     * Удаляем глобальную ссылку
     * на текущую публикацию.
     *
     * Компоненты темы не должны
     * получать отклонённую запись
     * через get_post() без аргументов.
     */
    $GLOBALS['post'] = null;


    /*
     * Устанавливаем HTTP-статус.
     */
    status_header( 404 );


    /*
     * Ответ об отказе не должен
     * публично кэшироваться.
     */
    nocache_headers();


    /*
     * Каноническое перенаправление
     * не должно отменять решение
     * об отказе в доступе.
     */
    remove_action(
        'template_redirect',
        'redirect_canonical'
    );


    /*
     * Исключаем перенаправление
     * через механизм прежних slug.
     */
    remove_action(
        'template_redirect',
        'wp_old_slug_redirect'
    );
}


/**
 * Проверяет доступность отдельной статьи
 * перед выбором шаблона отображения.
 *
 * Контроль применяется к публичному
 * singular-запросу обычной записи.
 *
 * Записи других разделов сохраняют
 * штатное поведение WordPress.
 *
 * @return void
 */
function dilitant_land_enforce_blog_article_visibility(): void {
    /*
     * Административные запросы
     * обслуживаются соответствующими
     * механизмами WordPress.
     */
    if ( is_admin() ) {
        return;
    }


    /*
     * AJAX имеет отдельный
     * механизм авторизации.
     */
    if ( wp_doing_ajax() ) {
        return;
    }


    /*
     * REST API не является
     * шаблонным HTTP-запросом.
     *
     * Его политика доступа должна
     * проверяться самостоятельно.
     */
    if (
        defined( 'REST_REQUEST' )
        && REST_REQUEST
    ) {
        return;
    }


    /*
     * Контроль относится к отдельным
     * обычным записям WordPress.
     *
     * Каталог, страницы, архивы
     * и пользовательские типы записей
     * не должны изменяться.
     */
    if ( ! is_singular( 'post' ) ) {
        return;
    }


    /*
     * Получаем непосредственно
     * разрешённый объект запроса.
     */
    $post = get_queried_object();

    if ( ! $post instanceof WP_Post ) {
        return;
    }


    /*
     * Устанавливаем принадлежность
     * записи к Article Model.
     *
     * Остальные записи WordPress
     * обслуживаются без вмешательства.
     */
    if (
        ! dilitant_land_is_blog_article(
            $post
        )
    ) {
        return;
    }


    /*
     * Делегируем решение о допустимости
     * отображения Article Model.
     *
     * Публичный запрос и Preview
     * проверяются раздельно.
     */
    if (
        ! dilitant_land_can_render_blog_article(
            $post
        )
    ) {
        dilitant_land_reject_blog_article();

        return;
    }


    /*
     * Авторизованный предварительный
     * просмотр не должен публично
     * кэшироваться.
     */
    if ( is_preview() ) {
        nocache_headers();
    }
}


/*
 * Регистрируем обработчик контроля
 * доступа до штатных механизмов
 * канонического перенаправления.
 *
 * Приоритет 1 сохраняется
 * для совместимости с AM-D03
 * и существующими испытаниями.
 */
add_action(
    'template_redirect',
    'dilitant_land_enforce_blog_article_visibility',
    1
);