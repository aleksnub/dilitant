<?php
/**
 * Точка входа HTTP Test Bootstrap.
 *
 * Нормативная основа:
 *     ТП-03 — Editorial
 *     EDC-01 — Article Model
 *     AM-D03 — Public Visibility
 *     HTTP-D01 — Environment
 *     HTTP-D02 — Fixtures & Authentication
 *     HF-D01 — Shared Test Bootstrap
 *
 * Ответственность:
 *     - подключение общей испытательной инфраструктуры;
 *     - подключение компонентов HTTP Bootstrap;
 *     - предварительная проверка окружения;
 *     - загрузка действительного WordPress;
 *     - подключение существующих Article Fixtures;
 *     - окончательная проверка окружения;
 *     - публикация признака готовности.
 *
 * Компонент предназначен исключительно
 * для PHP CLI внутри HTTP test container.
 *
 * Допустимый контейнер:
 *
 *     dilitant_land_http_test
 *
 * Допустимая база:
 *
 *     dilitant_land_test
 *
 * Компонент не должен подключаться
 * через существующий editorial/bootstrap.php.
 *
 * Рабочий wp-config.php не используется.
 *
 * Испытательные объекты не создаются
 * при подключении данного файла.
 *
 * STDOUT резервируется для машинных результатов
 * вызывающих PHP-компонентов.
 */

declare(strict_types=1);


/*
 * --------------------------------------------------
 * 1. Ограничение режима исполнения
 * --------------------------------------------------
 */

if (PHP_SAPI !== 'cli') {
    http_response_code(403);

    exit(1);
}


/*
 * --------------------------------------------------
 * 2. Подключение типизированных ошибок
 * --------------------------------------------------
 */

require_once __DIR__
    . '/bootstrap/errors.php';


/*
 * --------------------------------------------------
 * 3. Инициализация HTTP Bootstrap
 * --------------------------------------------------
 */

try {
    /*
     * ----------------------------------------------
     * 3.1. Общая испытательная инфраструктура
     * ----------------------------------------------
     */

    require_once dirname(__DIR__)
        . '/support/constants.php';


    require_once dirname(__DIR__)
        . '/support/assertions.php';


    /*
     * ----------------------------------------------
     * 3.2. Функциональные компоненты Bootstrap
     * ----------------------------------------------
     */

    require_once __DIR__
        . '/bootstrap/environment.php';


    require_once __DIR__
        . '/bootstrap/isolation.php';


    require_once __DIR__
        . '/bootstrap/interfaces.php';


    require_once __DIR__
        . '/bootstrap/initialization.php';


    /*
     * ----------------------------------------------
     * 3.3. Предварительные проверки
     * ----------------------------------------------
     *
     * Выполняются до загрузки WordPress.
     */

    dilitant_http_bootstrap_preinitialize();


    /*
     * ----------------------------------------------
     * 3.4. Загрузка WordPress
     * ----------------------------------------------
     *
     * Подключение выполняется в глобальной
     * области видимости.
     *
     * Используется смонтированный HTTP wp-config.php.
     */

    require_once __DIR__
        . '/bootstrap/wordpress.php';


    /*
     * ----------------------------------------------
     * 3.5. Проверка фактической изоляции
     * ----------------------------------------------
     *
     * Выполняется до подключения существующей
     * инфраструктуры испытательных объектов.
     */

    dilitant_http_verify_wordpress_isolation();


    /*
     * ----------------------------------------------
     * 3.6. Подключение Article Fixtures
     * ----------------------------------------------
     *
     * Переиспользуется существующая реализация.
     *
     * Новый экземпляр DilitantArticleFixtures
     * на данном этапе не создаётся.
     */

    require_once dirname(__DIR__)
        . '/fixtures.php';


    /*
     * ----------------------------------------------
     * 3.7. Окончательная проверка
     * ----------------------------------------------
     */

    dilitant_http_bootstrap_finalize();


} catch (Throwable $error) {
    dilitant_http_bootstrap_abort(
        $error
    );
}


/*
 * --------------------------------------------------
 * 4. Завершение инициализации
 * --------------------------------------------------
 *
 * После успешного подключения доступны:
 *
 *     DILITANT_TEST_DB_NAME
 *
 *     DILITANT_TEST_TABLE_PREFIX
 *
 *     DILITANT_HTTP_BOOTSTRAP_READY
 *
 *     dilitant_test_assert()
 *
 *     dilitant_test_assert_same()
 *
 *     dilitant_test_normalize_ids()
 *
 *     dilitant_test_query_ids()
 *
 *     dilitant_http_require_bootstrap()
 *
 *     dilitant_http_get_bootstrap_identity()
 *
 *     DilitantArticleFixtures
 *
 * Диагностические сообщения об успешной
 * инициализации намеренно не выводятся.
 *
 * Вызывающий компонент самостоятельно
 * формирует машинный результат операции.
 */